/**
 * Generates `src/theme/icon-glyphs.generated.ts`: the Material Symbols code
 * points for every Android icon referenced in `src/theme/icons.ts`.
 *
 * This lets the Icon component render glyphs synchronously from the preloaded
 * Material Symbols font (no per-icon async font check / blank first frame).
 *
 * Usage: npm run generate:icons
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

// expo-symbols' main entry lives in build/, next to android/symbols.json.
const symbolsPath = join(
  dirname(require.resolve('expo-symbols', { paths: [root] })),
  'android/symbols.json'
);
const symbols = JSON.parse(readFileSync(symbolsPath, 'utf8'));

const registry = readFileSync(join(root, 'src/theme/icons.ts'), 'utf8');
const names = [...new Set([...registry.matchAll(/android:\s*'([a-z0-9_]+)'/g)].map((m) => m[1]))].sort();

const missing = names.filter((name) => symbols[name] === undefined);
if (missing.length) {
  console.error(`Unknown Material Symbols: ${missing.join(', ')}`);
  process.exit(1);
}

const body = names.map((name) => `  ${name}: 0x${symbols[name].toString(16)},`).join('\n');
const output = `// Generated by scripts/generate-icon-glyphs.mjs — do not edit by hand.
export const iconGlyphs: Record<string, number> = {
${body}
};
`;

writeFileSync(join(root, 'src/theme/icon-glyphs.generated.ts'), output);
console.log(`Wrote ${names.length} glyphs.`);
